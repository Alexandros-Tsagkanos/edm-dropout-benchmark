#!/usr/bin/env python3
"""
One-click runner: a single-seed run of EVERY dataset.

Launch it - double-click run_all.bat (Windows), run_all.command (macOS), or
run_all.sh (Linux), or from a terminal run `python run_all.py`. It runs, in order:
  1. Realinho single-seed pipeline  (DATASETS/realinho/run_single.py)
  2. OULAD single-seed pipeline      (DATASETS/oulad/run_single.py)
  3. Real-text protocol validation   (DATASETS/forum_urgency/phase9b_realtext.py)
writing everything under RESULTS/. ~20 minutes total on a modern CPU (no GPU);
most of that is OULAD, whose 32k rows make its phases slower than Realinho's.
Dependencies install themselves from requirements.txt on first run.

No report (PDF, TeX, or otherwise) is produced - the technical report in
FINAL REPORT/ is hand-written, not generated by this code.

For a dataset's ten-seed study, run the run_multiseed.py inside its DATASETS
folder, e.g.  python DATASETS/realinho/run_multiseed.py 10
         or   python DATASETS/oulad/run_multiseed.py next
"""
from __future__ import annotations
import os, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CODE = ROOT / "CODE"

# Each entry is a single-seed run for one dataset, executed in order.
RUNS = [
    ("Realinho single-seed (phases 1-10 + SMOTE + bootstrap)",
     ROOT / "DATASETS" / "realinho" / "run_single.py"),
    ("OULAD single-seed (prep + phases 2-8 + SMOTE)",
     ROOT / "DATASETS" / "oulad" / "run_single.py"),
    ("Forum real-text protocol validation (frozen-DistilBERT)",
     ROOT / "DATASETS" / "forum_urgency" / "phase9b_realtext.py"),
]

# Import names (not pip names) needed before anything will run.
REQUIRED = ["numpy", "pandas", "sklearn", "scipy", "matplotlib", "seaborn",
            "torch", "xgboost", "transformers", "imblearn"]


def ensure_deps():
    """Install anything missing from requirements.txt (first run only)."""
    import importlib.util
    missing = [m for m in REQUIRED if importlib.util.find_spec(m) is None]
    if not missing:
        return
    print(f"[setup] installing missing dependencies: {', '.join(missing)}")
    subprocess.run([sys.executable, "-m", "pip", "install", "-r",
                    str(ROOT / "requirements.txt")], check=True)


def main():
    print(f"[setup] python : {sys.version.split()[0]}")
    ensure_deps()
    env = os.environ.copy()
    env["PYTHONUTF8"] = "1"
    # Make CODE/ importable for the forum check (invoked directly below); the
    # run_single.py scripts set their own PYTHONPATH as well.
    env["PYTHONPATH"] = str(CODE) + (os.pathsep + env["PYTHONPATH"]
                                     if env.get("PYTHONPATH") else "")
    t0 = time.time()
    for label, script in RUNS:
        print(f"\n########## {label} ##########", flush=True)
        rc = subprocess.run([sys.executable, str(script)], cwd=str(ROOT), env=env).returncode
        if rc != 0:
            print(f"[FAIL] {label} exited with code {rc}.")
            sys.exit(rc)
    print(f"\nAll datasets complete in {(time.time() - t0) / 60:.1f} min.")
    print("  outputs -> RESULTS/   (per-dataset single_seed/ folders + forum_urgency/)")
    print("  ten-seed studies -> run DATASETS/<dataset>/run_multiseed.py")


if __name__ == "__main__":
    main()
